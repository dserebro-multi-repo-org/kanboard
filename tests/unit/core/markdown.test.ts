import { readFileSync } from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { Container } from '../../../src/core/container/container.js';
import { Markdown } from '../../../src/core/markdown.js';

interface Fixture { input: string; public: boolean; output: string }

function makeContainer(): Container {
  const users: Record<string, { id: number; username: string; name: string }> = {
    admin: { id: 1, username: 'admin', name: '' },
    'firstname.lastname': { id: 2, username: 'firstname.lastname', name: 'Firstname Lastname' },
  };
  const url = {
    to(controller: string, action: string, params: Record<string, string | number> = {}, _anchor = '', absolute = false): string {
      let q = `?controller=${controller}&action=${action}`;
      for (const [k, v] of Object.entries(params)) q += `&${k}=${v}`;
      return (absolute ? 'http://localhost/' : '') + q;
    },
  };
  const c = new Container<Record<string, unknown>>();
  c.set('helper', { get: () => url });
  c.set('userCacheDecorator', { getByUsername: (n: string) => users[n] ?? null });
  c.set('taskFinderModel', {});
  c.set('memoryCache', { proxy: (_o: unknown, _m: string, id: string | number) => (Number(id) === 1 ? 'tok1' : '') });
  return c as unknown as Container;
}

async function render(text: string, isPublic = false): Promise<string> {
  const md = new Markdown(makeContainer(), isPublic);
  md.setSafeMode(true).setMarkupEscaped(true).setBreaksEnabled(true);
  return md.text(text);
}

const fixtures = JSON.parse(readFileSync(path.resolve('tests/fixtures/markdown/expected.json'), 'utf8')) as Fixture[];

describe('Markdown (ported from TextHelperTest)', () => {
  it('renders task links', async () => {
    expect(await render('Test')).toBe('<p>Test</p>');
    expect(await render('#123')).toBe('<p><a href="?controller=TaskViewController&amp;action=show&amp;task_id=123">#123</a></p>');
    expect(await render('Task #123', true)).toBe('<p>Task #123</p>');
    expect(await render('Task #1', true)).toBe('<p>Task <a href="http://localhost/?controller=TaskViewController&amp;action=readonly&amp;token=tok1&amp;task_id=1">#1</a></p>');
    expect(await render('[item #123 is here](http://localhost)')).toBe('<p><a href="http://localhost">item #123 is here</a></p>');
    expect(await render('#123 extra text not consumed')).toBe('<p><a href="?controller=TaskViewController&amp;action=show&amp;task_id=123">#123</a> extra text not consumed</p>');
  });

  it('renders user mentions', async () => {
    const admin = '<a href="?controller=UserViewController&amp;action=profile&amp;user_id=1" class="user-mention-link" title="admin" aria-label="admin">@admin</a>';
    expect(await render('Text @admin @notfound')).toBe(`<p>Text ${admin} @notfound</p>`);
    expect(await render('Text @admin,')).toBe(`<p>Text ${admin},</p>`);
    expect(await render('Text @admin.')).toBe(`<p>Text ${admin}.</p>`);
    expect(await render('Text @admin @notfound', true)).toBe('<p>Text @admin @notfound</p>');
    expect(await render('[mention @admin at localhost](http://localhost)')).toBe('<p><a href="http://localhost">mention @admin at localhost</a></p>');
  });

  it('rejects the javascript scheme', async () => {
    expect(await render('[XSS](javascript:alert(1))')).toBe('<p><a href="javascript%3Aalert(1)">XSS</a></p>');
  });

  it('escapes raw HTML in safe mode and handles unsafe images', async () => {
    expect(await render('<script>alert(1)</script>')).toBe('<p>&lt;script&gt;alert(1)&lt;/script&gt;</p>');
    expect(await render('![x](javascript:alert(1))')).toContain('src="javascript%3Aalert(1)"');
  });
});

describe('Markdown fixtures generated by the PHP implementation (Parsedown)', () => {
  it.each(fixtures.map((f, i) => [i, f] as const))('fixture %i', async (_i, f) => {
    expect(await render(f.input, f.public)).toBe(f.output);
  });
});
