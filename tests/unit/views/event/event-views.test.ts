import path from 'node:path';
import { beforeAll, describe, expect, it } from 'vitest';
import { prepareEventVars } from '../../../../src/views/prepare/event.js';
import { compareToPhp, loadCases, makeViewContext } from '../golden-views.js';

const dir = import.meta.dirname;
const cases = loadCases(dir);
let ctx: Awaited<ReturnType<typeof makeViewContext>>;

beforeAll(async () => {
  ctx = await makeViewContext();
});

describe('event views match the output of the PHP templates (fixtures generated by gen-php-golden.php)', () => {
  it.each(cases.map((c) => [c.name, c] as const))('%s', async (_name, c) => {
    const vars = await prepareEventVars(ctx.helpers, c.vars);
    const { actual, expected } = compareToPhp(ctx.template, c, vars, dir);
    expect(actual).toBe(expected);
  });

  it('every event template has a case', () => {
    const covered = new Set(cases.map((c) => c.template));
    for (const f of ['comment_create', 'comment_delete', 'comment_update', 'events', 'subtask_create', 'subtask_delete', 'subtask_update', 'task_assignee_change', 'task_close', 'task_create', 'task_file_create', 'task_file_destroy', 'task_internal_link_create_update', 'task_internal_link_delete', 'task_move_column', 'task_move_position', 'task_move_project', 'task_move_swimlane', 'task_open', 'task_update']) {
      expect(covered.has(`event/${f}`), f).toBe(true);
      expect(ctx.template.exists(`event/${f}`), f).toBe(true);
    }
    expect(path.basename(dir)).toBe('event');
  });
});
