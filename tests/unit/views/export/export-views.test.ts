import { beforeAll, describe, expect, it } from 'vitest';
import { compareToPhp, loadCases, makeViewContext, setRouter } from '../golden-views.js';

const dir = import.meta.dirname;
const cases = loadCases(dir);
let ctx: Awaited<ReturnType<typeof makeViewContext>>;

beforeAll(async () => {
  ctx = await makeViewContext();
});

describe('export views match the output of the PHP templates (fixtures generated by gen-php-golden.php)', () => {
  it.each(cases.map((c) => [c.name, c] as const))('%s', (_name, c) => {
    if (c.router !== undefined) setRouter(ctx.container, c.router[0], c.router[1]);
    const { actual, expected } = compareToPhp(ctx.template, c, c.vars, dir);
    expect(actual).toBe(expected);
  });
});
