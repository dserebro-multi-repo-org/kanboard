import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { sprintf, toFixedPhp } from './sprintf.js';

/** Same pattern as the PHP `Translator::load()`. */
const LOCALE_CODE = /^[a-z]{2}(_[a-zA-Z]{2,4}(_[a-zA-Z]{2,4})?)?$/;

/** PHP `htmlspecialchars($v, ENT_QUOTES, 'UTF-8', false)`: existing entities are not double encoded. */
export function escapeHtml(value: unknown): string {
  const str = value === null || value === undefined || value === false ? '' : value === true ? '1' : String(value);
  return str
    .replace(/&(?!(?:[a-zA-Z][a-zA-Z0-9]*|#[0-9]+|#[xX][0-9a-fA-F]+);)/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

/** PHP `number_format()`. */
export function numberFormat(num: number, decimals = 0, decPoint = '.', thousandsSep = ','): string {
  const fixed = toFixedPhp(Number(num), Math.max(0, decimals));
  const negative = fixed.startsWith('-');
  const [int = '0', frac] = (negative ? fixed.slice(1) : fixed).split('.');
  const grouped = int.replace(/\B(?=(\d{3})+(?!\d))/g, thousandsSep);
  return (negative ? '-' : '') + grouped + (frac !== undefined && decimals > 0 ? decPoint + frac : '');
}

/**
 * Translator, port of `Kanboard\Core\Translator`. Locales are kept in a process-wide map like the PHP static
 * property; JSON locale files (generated by scripts/convert-locales.php) are read lazily from `locales/`.
 */
export class Translator {
  static locales: Record<string, string> = {};
  private static instance: Translator | null = null;

  static getInstance(): Translator {
    Translator.instance ??= new Translator();
    return Translator.instance;
  }

  /** Default locales folder: `<project root>/locales`, valid from both `src/` and `dist/`. */
  static getDefaultFolder(): string {
    return path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..', 'locales');
  }

  /** Get a translation, arguments are HTML escaped. */
  translate(identifier: string, ...args: unknown[]): string {
    return sprintf(this.get(identifier, identifier), ...args.map(escapeHtml));
  }

  /** Get a translation with no HTML escaping. */
  translateNoEscaping(identifier: string, ...args: unknown[]): string {
    return sprintf(this.get(identifier, identifier), ...args);
  }

  number(value: number | string): string {
    return numberFormat(
      Number(value),
      Number(this.get('number.decimals', '2')),
      this.get('number.decimals_separator', '.'),
      this.get('number.thousands_separator', ','),
    );
  }

  currency(amount: number | string): string {
    const position = this.get('currency.position', 'before');
    const symbol = this.get('currency.symbol', '$');
    let str = '';
    if (position === 'before') str += symbol;
    str += this.number(amount);
    if (position === 'after') str += ` ${symbol}`;
    return str;
  }

  get(identifier: string, defaultValue = ''): string {
    return Object.hasOwn(Translator.locales, identifier) ? Translator.locales[identifier]! : defaultValue;
  }

  /** Load (merge) a locale such as `fr_FR`; returns false for invalid codes, unknown locales or traversal. */
  static load(languageCode: string, localeDir = ''): boolean {
    if (!LOCALE_CODE.test(languageCode)) return false;
    const dir = localeDir === '' ? Translator.getDefaultFolder() : localeDir;

    let baseDir: string;
    let realFile: string;
    try {
      baseDir = fs.realpathSync(dir);
      realFile = fs.realpathSync(path.join(dir, `${languageCode}.json`));
    } catch {
      return false;
    }
    if (!realFile.startsWith(baseDir + path.sep)) return false;

    try {
      const data = JSON.parse(fs.readFileSync(realFile, 'utf8')) as Record<string, unknown>;
      for (const [key, value] of Object.entries(data)) Translator.locales[key] = String(value);
    } catch {
      return false;
    }
    return true;
  }

  static unload(): void {
    Translator.locales = {};
  }
}
